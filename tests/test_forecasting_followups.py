def test_retail_target_future_mutation_cannot_change_first_median(retail_inputs):
    panel, original = retail_inputs
    origin = original.origin.min()
    before = retail_median_predictions(panel, original)
    changed = panel.copy()
    changed.loc[origin:] = 1e7
    changed_predictions = predict(changed, sorted(original.origin.unique()))
    after = retail_median_predictions(changed, changed_predictions)
    mask = (before.origin == origin) & (before.model == MEDIAN_MODEL)
    np.testing.assert_array_equal(before.loc[mask, 'prediction'], after.loc[mask, 'prediction'])
    np.testing.assert_array_equal(before.training_weekly_scale, after.training_weekly_scale)
    assert after.loc[mask, 'observed'].eq(7e7).all()


def test_every_code_and_method_is_in_leave_one_out_scores():
    # Two weeks repeat each hand-designed error, so product macro scores have
    # transparent denominators. Capitalization remains part of code identity.
    rows = []
    methods = [*MODELS, MEDIAN_MODEL]
    for method_index, model in enumerate(methods):
        for product, actual, forecast, scale in [('a', 1, 1 + method_index, 2),
                                                 ('B', 3, 2 + 2 * method_index, 4),
                                                 ('b', 2, 5 - method_index, 8)]:
            for origin in pd.to_datetime(['2011-01-03', '2011-01-10']):
                rows.append({'model': model, 'product': product, 'origin': origin,
                             'observed': actual, 'prediction': forecast, 'training_weekly_scale': scale})
    scores = retail_leave_one_out(pd.DataFrame(rows))
    assert len(scores) == 3 * 6
    assert set(scores.excluded_product) == {'a', 'B', 'b'}
    assert scores.groupby('excluded_product').model.nunique().eq(6).all()
    assert scores.product_weeks.eq(4).all()
    row = scores.loc[(scores.excluded_product == 'B') & (scores.model == 'zero')].iloc[0]
    assert row.macro_scaled_mae == .1875  # (0/2 + 3/8)/2
    assert row.unit_mae == 1.5  # (0 + 3)/2
    row = scores.loc[(scores.excluded_product == 'b') & (scores.model == MEDIAN_MODEL)].iloc[0]
    assert row.macro_scaled_mae == 2.375  # (5/2 + 9/4)/2
    assert row.unit_mae == 7  # (5 + 9)/2


def test_last_week_bias_telescopes_even_with_large_allocation_errors():
    dates = pd.date_range('2010-12-27', periods=28)
    panel = pd.DataFrame({'code': np.repeat([1., 100., 2., 4.], 7)}, index=dates)
    rows = pd.DataFrame({'origin': pd.to_datetime(['2011-01-03', '2011-01-10', '2011-01-17']),
                         'product': 'code', 'model': 'last_week',
                         'prediction': [7., 700., 14.], 'observed': [700., 14., 28.]})
    audit = last_week_bias_identity(panel, rows).iloc[0]
    assert audit.pretest_week_units == 7 and audit.final_week_units == 28
    assert audit.signed_total_error_units == -21
    assert audit.identity_residual_units == 0
    assert (rows.prediction - rows.observed).abs().mean() > 400
    with pytest.raises(ValueError, match='contiguous'):
        last_week_bias_identity(panel, rows.drop(index=1))


def test_report_writers_only_add_followup_artifacts(tmp_path, co2_inputs, retail_inputs):
    co2_out, retail_out = tmp_path / 'co2', tmp_path / 'retail'
    co2_out.mkdir()
    retail_out.mkdir()
    for out in [co2_out, retail_out]:
        (out / 'metrics.json').write_text('original sentinel')
    co2_report = co2_followup(co2_out, *co2_inputs)
    retail_report = retail_followup(retail_out, *retail_inputs)
    for out, report in [(co2_out, co2_report), (retail_out, retail_report)]:
        assert 'Post-publication exploratory follow-up' in report
        assert (out / 'metrics.json').read_text() == 'original sentinel'
        assert all(p.name.startswith('followup-') for p in out.iterdir() if p.name != 'metrics.json')
    saved = json.loads((retail_out / 'followup-metrics.json').read_text())
    assert len(saved['primary']) == 6
    exclusions = pd.read_csv(retail_out / 'followup-leave-one-code-out.csv')
    assert len(exclusions) == 18
    scores = pd.read_csv(co2_out / 'followup-scores.csv')
    assert len(scores) == 24
