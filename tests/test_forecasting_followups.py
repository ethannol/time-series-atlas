    rows = []
    for model, values in saved.items():
        for i, origin in enumerate(origins):
            for j, horizon in enumerate([1, 12, 36]):
                rows.append({'origin_month': origin, 'target': origin + pd.DateOffset(months=horizon),
                             'horizon': horizon, 'model': model,
                             'split': 'calibration' if i < 2 else 'test', 'actual': actuals[i][j],
                             'prediction': float(values[i][j]), 'lower': float(values[i][j] - 3),
                             'upper': float(values[i][j] + 5),
                             'site_substitution': i == 3 and horizon == 36})
    return frame, pd.DataFrame(rows)


