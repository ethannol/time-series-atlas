def test_hand_calculated_intermittent_recurrences():
    # First sale at day 3: size=6, interval=3, probability=1/3.
    # A zero makes probability=.3. Sale 8 after two days makes size=6.2,
    # interval=2.9, probability=.37. This independent fixture was recorded
    # in the original critic's manual arithmetic, not generated by a loop here.
    sba, tsb = intermittent_rates([0, 0, 6, 0, 8])
    assert sba == pytest.approx(.95 * 6.2 / 2.9)
    assert tsb == pytest.approx(.37 * 6.2)
    # The next consecutive positive has a one-day gap, not zero or two.
    # size=.9*6.2+.1*10=6.58; interval=.9*2.9+.1=2.71;
    # occurrence probability=.9*.37+.1=.433.
    sba, tsb = intermittent_rates([0, 0, 6, 0, 8, 10])
    assert sba == pytest.approx(.95 * 6.58 / 2.71)
    assert tsb == pytest.approx(.433 * 6.58)


def test_co2_anchor_and_calibration_have_hand_checked_values(co2_inputs):
    frame, original = co2_inputs
    snapshot = original.copy(deep=True)
    combined, offsets, gaps = anchored_co2_predictions(frame, original)
    pd.testing.assert_frame_equal(original, snapshot)
    pd.testing.assert_frame_equal(combined.iloc[:len(original)].reset_index(drop=True), snapshot)
    expanding = combined.loc[combined.model == 'linear_expanding_anchored']
    np.testing.assert_allclose(expanding.prediction, [11, 14, 22, 16, 19, 27, 18, 21, 29, 20, 23, 31])
    # Calibration residuals are 3 and 7 for each expanding horizon; linear
    # sample interpolation gives 3.4 and 6.6, not min/max or test residuals.
    first_offsets = offsets.loc[offsets.model == 'linear_expanding_anchored']
    np.testing.assert_allclose(first_offsets.lower_offset, 3.4)
    np.testing.assert_allclose(first_offsets.upper_offset, 6.6)
    recent36 = offsets.loc[(offsets.model == 'linear_120months_anchored') & (offsets.horizon == 36)].iloc[0]
    assert recent36.lower_offset == pytest.approx(.1)
    assert recent36.upper_offset == pytest.approx(.9)
    np.testing.assert_allclose(gaps.loc[gaps.model == 'linear_expanding', 'origin_gap'], [2, 6, 7, 8])
    assert first_offsets.n_calibration.eq(2).all()


def test_co2_future_mutation_cannot_change_issued_forecast_or_calibration(co2_inputs):
    frame, original = co2_inputs
    before, calibration_before, _ = anchored_co2_predictions(frame, original)
    issued = pd.Timestamp('2005-12-01')
    changed_frame = frame.copy()
    changed_frame.loc[changed_frame.index > issued, 'average'] = 1e8
    changed = original.copy()
    changed.loc[changed.target > issued, 'actual'] = -1e8
    after, calibration_after, _ = anchored_co2_predictions(changed_frame, changed)
    pd.testing.assert_frame_equal(calibration_before, calibration_after)
    cols = ['model', 'horizon', 'prediction', 'lower', 'upper']
    pd.testing.assert_frame_equal(before.loc[before.origin_month == issued, cols].reset_index(drop=True),
                                  after.loc[after.origin_month == issued, cols].reset_index(drop=True))
    assert not before.loc[before.split == 'test', 'actual'].equals(after.loc[after.split == 'test', 'actual'])


def test_co2_site_sensitivity_removes_targets_without_recalibration(co2_inputs):
    combined, _, _ = anchored_co2_predictions(*co2_inputs)
    scores = co2_followup_scores(combined)
    primary = scores['test']['linear_expanding_anchored/36']
    sensitivity = scores['exclude_site_targets']['linear_expanding_anchored/36']
    assert primary['n'] == 2 and sensitivity['n'] == 1
    assert primary['mae'] == 2 and primary['bias'] == -2
    assert sensitivity['mae'] == 1 and sensitivity['bias'] == -1
    assert primary['width80'] == pytest.approx(3.2)
    assert sensitivity['width80'] == pytest.approx(3.2)
    assert primary['interval_score80'] == pytest.approx(17.2)
    assert sensitivity['interval_score80'] == pytest.approx(27.2)
    assert len(scores['exclude_site_targets']) == 12


def test_co2_rejects_unusable_origin_missing_december_and_late_calibration(co2_inputs):
    frame, original = co2_inputs
    bad_frame = frame.copy()
    bad_frame.iloc[0, bad_frame.columns.get_loc('usable')] = False
    with pytest.raises(ValueError, match='usable observed'):
        anchored_co2_predictions(bad_frame, original)
    with pytest.raises(ValueError, match='12- and 36-month'):
        anchored_co2_predictions(frame, original.drop(index=1))
    changed = original.copy()
    changed.loc[0, 'target'] = pd.Timestamp('2005-12-01')
    with pytest.raises(ValueError, match='precede'):
        anchored_co2_predictions(frame, changed)


def test_weekly_median_uses_52_week_totals_and_exact_calendar_boundary():
    origin = pd.Timestamp('2011-01-03')
    dates = pd.date_range(origin - pd.Timedelta(days=365), origin + pd.Timedelta(days=7))
    series = pd.Series(1e8, index=dates)
    history_dates = pd.date_range(origin - pd.Timedelta(days=364), periods=364)
    # Each week has all sales on Monday: weekly totals are 1..52; daily median is 0.
    history = np.zeros(364)
    history[::7] = np.arange(1, 53)
    series.loc[history_dates] = history
    assert trailing_weekly_median(series, origin) == 26.5
    series.loc[origin:] = -999  # Targets/future are outside the validated history.
    assert trailing_weekly_median(series, origin) == 26.5
    with pytest.raises(ValueError, match='364 complete'):
        trailing_weekly_median(series.drop(history_dates[6]), origin)
    series.loc[history_dates[6]] = np.nan
    with pytest.raises(ValueError, match='364 complete'):
        trailing_weekly_median(series, origin)
    with pytest.raises(ValueError, match='Monday'):
        trailing_weekly_median(series, origin + pd.Timedelta(days=1))


